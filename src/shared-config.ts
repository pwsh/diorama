// Shared configurations — PURE helpers. ZERO imports (the flights.ts idiom):
// no DOM, no network, no Planner, no clock. Every function is a deterministic
// transform; the Planner owns the fetches and the service calls.
//
// ── Why this exists ─────────────────────────────────────────────────────────
// The config registry lives in HA `frontend.user_data`, which HA keys PER USER:
// a second HA user (kiosk tablet account, family member) opens the panel and
// sees only an empty Default config. Shared configs live instead as STATIC
// FILES under `<config>/www/diorama/shared/` — `index.json` + `<id>.json` (the
// SAME export envelope exportConfig produces, so a shared file is also
// importable by hand) — which every HA user can READ through `/local/…`.
//
// ── Writes ──────────────────────────────────────────────────────────────────
// A browser cannot write HA's config directory, so writes go through a
// user-defined `shell_command` the admin pastes into configuration.yaml (the
// flights `rest_command` precedent: HA does the privileged part; the YAML is
// generated by `sharedWriteYaml` from the SAME field names
// `sharedWriteServiceData` sends, so the two can never disagree).
//
// Linux caps ONE argv string at 128 KiB (MAX_ARG_STRLEN), and a shell_command
// template hands each rendered field over as one argv string. So the client
// base64-encodes the JSON (base64 needs no quoting and survives shlex) and
// sends it in chunks of at most SHARED_CHUNK_B64 characters: `{name, seq,
// total, data}`. The script appends each chunk to `<name>.part<seq>` (seq 0
// truncates first — a restarted sequence never inherits a stale tail) and on
// the LAST chunk decodes the whole thing, validates it parses as JSON, writes
// `<name>.json.tmp` and `os.replace`s it over `<name>.json` — ATOMIC, so a
// reader fetching mid-write sees either the old file or the new one, never a
// half-written one.

export const SHARED_WRITE_COMMAND = 'diorama_shared_write';
// Relative to the HA config dir. Served by HA at /local/diorama/shared/.
export const SHARED_DIR_REL = 'www/diorama/shared';
export const SHARED_URL_PATH = '/local/diorama/shared';
// 96 KiB of base64 per chunk — comfortably under the 128 KiB argv cap even
// after the other arguments, and a multiple of 4 (each chunk is whole base64
// quanta, although the script decodes the concatenation anyway).
export const SHARED_CHUNK_B64 = 96 * 1024;
// The script's own sanity cap on `total` (≈ 96 MB). Mirrored here so the client
// refuses a payload the script would refuse.
export const SHARED_MAX_CHUNKS = 1000;
// Reserved basenames: `index` is the index, `_probe` the Test-write round trip.
export const SHARED_INDEX_NAME = 'index';
export const SHARED_PROBE_NAME = '_probe';
// File basename rule — the SAME regex the python script enforces. Excludes '.'
// and '/', so '..' and path separators can never reach the filesystem.
export const SHARED_NAME_RE = /^[a-z0-9_-]{1,64}$/;

export interface SharedIndexEntry { id: string; name: string; updatedAt: number; sharedBy?: string; }
export interface SharedIndex { version: 1; configs: SharedIndexEntry[]; }

// A valid file basename, or null. Never throws.
export function sanitizeSharedName(name: unknown): string | null {
  return typeof name === 'string' && SHARED_NAME_RE.test(name) ? name : null;
}

// May this config id be published as `<id>.json`? (valid basename AND not one
// of the reserved names.)
export function sharedConfigIdOk(id: unknown): boolean {
  const n = sanitizeSharedName(id);
  return n !== null && n !== SHARED_INDEX_NAME && n !== SHARED_PROBE_NAME;
}

// UTF-8 → base64 without the `btoa(unescape(encodeURIComponent()))` trick
// (deprecated) and without blowing the argument limit of fromCharCode.apply.
export function utf8ToBase64(s: string): string {
  const bytes = new TextEncoder().encode(s);
  let bin = '';
  for (let i = 0; i < bytes.length; i += 0x8000) {
    bin += String.fromCharCode.apply(null, Array.from(bytes.subarray(i, i + 0x8000)));
  }
  return btoa(bin);
}
export function base64ToUtf8(b64: string): string {
  const bin = atob(b64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return new TextDecoder().decode(bytes);
}

// Split a JSON payload into base64 chunks (the BASE64 is chunked, never the
// JSON — a cut through a multi-byte UTF-8 sequence would be harmless anyway
// because the script decodes the reassembled whole). Always ≥ 1 chunk.
export function sharedChunkPlan(json: string, chunkLen: number = SHARED_CHUNK_B64): { chunks: string[] } {
  const b64 = utf8ToBase64(json);
  const len = Math.max(4, Math.floor(chunkLen / 4) * 4);
  const chunks: string[] = [];
  for (let i = 0; i < b64.length; i += len) chunks.push(b64.slice(i, i + len));
  if (!chunks.length) chunks.push('');
  return { chunks };
}

// The ONE builder of the service data the write path sends. The field names
// here are exactly the `{{ … }}` names sharedWriteYaml renders.
export function sharedWriteServiceData(name: string, seq: number, total: number, chunk: string):
  { name: string; seq: number; total: number; data: string } {
  return { name, seq, total, data: chunk };
}

// The python script (each line top-level — no indentation, so it survives the
// YAML literal block's indent stripping). The partial file's NAME carries the
// last sequence number written (`<name>.part<seq>`): chunk s>0 is accepted only
// when `.part<s-1>` exists, so a dropped or interleaved chunk aborts the write
// (the previous `<name>.json` stays intact) instead of silently assembling a
// shorter-but-still-valid JSON. seq 0 deletes any stale partials first.
// Contains no `"`, `\`, `{{`, `{%` or `{#`, so it is safe inside the
// double-quoted shlex token AND as Jinja text.
const SHARED_WRITE_PY = [
  'import sys,os,re,base64,json,glob',
  'd,n,b=sys.argv[1],sys.argv[2],sys.argv[5]',
  's,t=int(sys.argv[3]),int(sys.argv[4])',
  "if not re.fullmatch('[a-z0-9_-]{1,64}',n) or not 0<=s<t<=" + SHARED_MAX_CHUNKS + ": sys.exit('diorama: bad name or sequence')",
  'os.makedirs(d,exist_ok=True)',
  "p=os.path.join(d,n+'.part')",
  "if s==0: [os.remove(x) for x in glob.glob(glob.escape(p)+'*')]",
  "elif not os.path.exists(p+str(s-1)): sys.exit('diorama: chunk out of sequence')",
  'else: os.replace(p+str(s-1),p+str(s))',
  "with open(p+str(s),'a') as h: h.write(b)",
  'if s<t-1: sys.exit(0)',
  'with open(p+str(s)) as h: raw=base64.b64decode(h.read(),validate=True)',
  'json.loads(raw)',
  "f=os.path.join(d,n+'.json')",
  "with open(f+'.tmp','wb') as h: h.write(raw)",
  "os.replace(f+'.tmp',f)",
  'os.remove(p+str(s))',
];

// The configuration.yaml block. `configDir` is HA's config directory as seen by
// the HA process (`/config` on HA OS / container installs).
export function sharedWriteYaml(configDir: string = '/config'): string {
  const dir = (String(configDir || '/config').replace(/["\\]/g, '').replace(/\/+$/, '') || '/config')
    + '/' + SHARED_DIR_REL;
  const f = (k: keyof ReturnType<typeof sharedWriteServiceData>) => `"{{ ${k} }}"`;
  return '# Diorama — shared floor plans. Writes ' + dir + '/<name>.json\n'
    + '# (served to every Home Assistant user at ' + SHARED_URL_PATH + '/).\n'
    + '# Restart Home Assistant after adding. Your config directory must already\n'
    + '# contain a www/ folder when HA starts, or /local/ is not served.\n'
    + 'shell_command:\n'
    + `  ${SHARED_WRITE_COMMAND}: |-\n`
    + '    python3 -c "\n'
    + SHARED_WRITE_PY.map(l => '    ' + l + '\n').join('')
    + `    " "${dir}" ${f('name')} ${f('seq')} ${f('total')} ${f('data')}\n`;
}

export function sharedUrl(baseUrl: string, name: string, v: string | number): string {
  const base = String(baseUrl || '').replace(/\/+$/, '');
  return `${base}${SHARED_URL_PATH}/${name}.json?v=${encodeURIComponent(String(v))}`;
}

// Parse a fetched index (string or already-parsed object). NEVER throws:
// garbage → an empty index. Entries need a publishable id; later duplicates of
// an id are dropped.
export function parseSharedIndex(json: unknown): SharedIndex {
  const out: SharedIndex = { version: 1, configs: [] };
  let o: unknown = json;
  if (typeof o === 'string') { try { o = JSON.parse(o); } catch { return out; } }
  if (!o || typeof o !== 'object') return out;
  const arr = (o as { configs?: unknown }).configs;
  if (!Array.isArray(arr)) return out;
  const seen = new Set<string>();
  for (const e of arr) {
    if (!e || typeof e !== 'object') continue;
    const r = e as Record<string, unknown>;
    if (!sharedConfigIdOk(r.id) || seen.has(r.id as string)) continue;
    const updatedAt = Number(r.updatedAt);
    const entry: SharedIndexEntry = {
      id: r.id as string,
      name: typeof r.name === 'string' && r.name.trim() ? r.name : (r.id as string),
      updatedAt: Number.isFinite(updatedAt) ? updatedAt : 0,
    };
    if (typeof r.sharedBy === 'string' && r.sharedBy) entry.sharedBy = r.sharedBy;
    seen.add(entry.id);
    out.configs.push(entry);
  }
  return out;
}

// Pure index edits (copy-on-write).
export function upsertSharedIndex(idx: SharedIndex, entry: SharedIndexEntry): SharedIndex {
  const configs = idx.configs.filter(c => c.id !== entry.id);
  configs.push({ ...entry });
  return { version: 1, configs };
}
export function removeFromSharedIndex(idx: SharedIndex, id: string): SharedIndex {
  return { version: 1, configs: idx.configs.filter(c => c.id !== id) };
}

// Does a failed service call mean "the shell_command was never configured"?
// HA answers an unknown service with `{code:'not_found', message:'Service
// shell_command.diorama_shared_write not found.'}` (newer cores add a
// `translation_key: 'service_not_found'`).
export function sharedErrorIsMissingService(err: unknown): boolean {
  if (!err) return false;
  if (typeof err === 'string') return /not[ _]found/i.test(err);
  if (typeof err !== 'object') return false;
  const e = err as Record<string, unknown>;
  if (e.code === 'not_found' || e.translation_key === 'service_not_found') return true;
  return typeof e.message === 'string' && /service .*not found|not_found/i.test(e.message);
}
