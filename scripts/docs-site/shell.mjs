// Site-wide sections shown in the sticky topbar. `href` is relative to the
// site root; sitePage() prefixes it by depth.
export const SITE_SECTIONS = [
  { key: 'home', label: 'Home', href: 'index.html' },
  { key: 'guide', label: 'Guide', href: 'guide/getting-started.html' },
  { key: 'models', label: 'Models', href: 'models/index.html' },
  { key: 'floorplans', label: 'Floor plans', href: 'floorplans/index.html' },
  // The live demo page is the full app (staged by scripts/docs-site/demo.mjs),
  // not a sitePage() emit, so it never carries section==='demo' and simply
  // never highlights — the relative href + ?demo query resolve fine at any depth.
  { key: 'demo', label: 'Live demo', href: 'demo/index.html?demo=ranch-3bed' },
];

/**
 * Full page wrapper.
 * @param {object} o
 * @param {string} o.title      document title (suffixed with "— Diorama")
 * @param {string} o.section    active SITE_SECTIONS key
 * @param {number} o.depth      directory depth below the site root (0 = root)
 * @param {string} o.main       inner HTML of <main>
 * @param {string} [o.sidebar]  optional sidebar HTML (nav links); omitted = full-width
 * @param {string} [o.version]  app version for the topbar meta
 * @param {string} [o.date]     build date for the topbar meta
 */
export function sitePage({ title, section, depth, main, sidebar, version, date }) {
  const prefix = '../'.repeat(depth);
  const nav = SITE_SECTIONS.map((s) =>
    `<a class="topnav-link${s.key === section ? ' active' : ''}" href="${prefix}${s.href}">${htmlEsc(s.label)}</a>`).join('');
  const meta = version ? `<span class="brand-meta">v${htmlEsc(version)}${date ? ' · ' + htmlEsc(date) : ''}</span>` : '';
  const menuBtn = sidebar
    ? `<button class="menu-btn" aria-label="Toggle navigation" onclick="document.body.classList.toggle('nav-open')">☰</button>` : '';
  const layout = sidebar
    ? `<div class="layout"><aside class="sidebar">${sidebar}</aside><main class="main">${main}</main></div>`
    : `<div class="layout"><main class="main main-solo">${main}</main></div>`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${htmlEsc(title)} — Diorama</title>
<link rel="stylesheet" href="${prefix}assets/site.css">
</head>
<body>
<header class="topbar">
${menuBtn}<a class="brand" href="${prefix}index.html">Diorama</a>
<nav class="topnav">${nav}</nav>
${meta}
</header>
${layout}
<script>
document.querySelectorAll('.nav-link').forEach(function(a){a.addEventListener('click',function(){document.body.classList.remove('nav-open');});});
</script>
</body>
</html>`;
}

// ── minimal markdown → HTML (guide pages) ─────────────────────────────────────
// Supports: # headings, paragraphs, - / 1. lists (one nesting level), ```
// fences, | tables, > quotes, **bold**, *italic*, `code`, [text](href),
// ![alt](src), --- rules. Enough for authored guide prose; not a general parser.
export function mdToHtml(md) {
  const lines = String(md).replace(/\r\n/g, '\n').split('\n');
  let out = '';
  let i = 0;
  // GitHub-style heading slugs (per-document unique) so in-page anchors work.
  const usedSlugs = new Map();
  const slugOf = (raw) => {
    const base = raw
      .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')   // links/images → text
      .replace(/[`*_]/g, '')                        // inline markers
      .toLowerCase()
      .replace(/[^a-z0-9\s-]/g, '')
      .trim()
      .replace(/\s+/g, '-') || 'section';
    const n = usedSlugs.get(base) || 0;
    usedSlugs.set(base, n + 1);
    return n === 0 ? base : `${base}-${n + 1}`;
  };
  const inline = (s) => htmlEsc(s)
    .replace(/!\[([^\]]*)\]\(([^)]+)\)/g, '<img loading="lazy" src="$2" alt="$1">')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>')
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[\s(])\*([^*\s][^*]*)\*/g, '$1<em>$2</em>');
  while (i < lines.length) {
    const ln = lines[i];
    if (/^\s*$/.test(ln)) { i++; continue; }
    if (/^```/.test(ln)) {
      const buf = [];
      i++;
      while (i < lines.length && !/^```/.test(lines[i])) buf.push(lines[i++]);
      i++;
      out += `<pre><code>${htmlEsc(buf.join('\n'))}</code></pre>\n`;
      continue;
    }
    const h = ln.match(/^(#{1,4})\s+(.*)$/);
    if (h) {
      const lvl = h[1].length;
      const id = slugOf(h[2]);
      out += `<h${lvl} id="${id}">${inline(h[2])}<a class="hlink" href="#${id}" aria-label="Link to this section">#</a></h${lvl}>\n`;
      i++; continue;
    }
    if (/^---+\s*$/.test(ln)) { out += '<hr>\n'; i++; continue; }
    if (/^\|/.test(ln)) {
      const rows = [];
      while (i < lines.length && /^\|/.test(lines[i])) rows.push(lines[i++]);
      const cells = (r) => r.replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
      let t = '<div class="table-wrap"><table><thead><tr>'
        + cells(rows[0]).map((c) => `<th>${inline(c)}</th>`).join('') + '</tr></thead><tbody>';
      for (const r of rows.slice(2)) t += '<tr>' + cells(r).map((c) => `<td>${inline(c)}</td>`).join('') + '</tr>';
      out += t + '</tbody></table></div>\n';
      continue;
    }
    if (/^>\s?/.test(ln)) {
      const buf = [];
      while (i < lines.length && /^>\s?/.test(lines[i])) buf.push(lines[i++].replace(/^>\s?/, ''));
      out += `<blockquote><p>${buf.map(inline).join('<br>')}</p></blockquote>\n`;
      continue;
    }
    const listM = ln.match(/^(\s*)([-*]|\d+\.)\s+/);
    if (listM) {
      const ordered = /\d/.test(listM[2]);
      const tag = ordered ? 'ol' : 'ul';
      let t = `<${tag}>`;
      while (i < lines.length) {
        const m = lines[i].match(/^(\s*)([-*]|\d+\.)\s+(.*)$/);
        if (!m) break;
        let item = m[3];
        i++;
        // nested one level
        let sub = '';
        while (i < lines.length) {
          const n = lines[i].match(/^\s{2,}([-*]|\d+\.)\s+(.*)$/);
          if (!n) break;
          sub += `<li>${inline(n[2])}</li>`;
          i++;
        }
        t += `<li>${inline(item)}${sub ? `<ul>${sub}</ul>` : ''}</li>`;
      }
      out += t + `</${tag}>\n`;
      continue;
    }
    // paragraph — consume until blank/structural line
    const buf = [ln];
    i++;
    while (i < lines.length && !/^\s*$/.test(lines[i]) && !/^(#{1,4}\s|```|\||>|---|\s*([-*]|\d+\.)\s)/.test(lines[i])) buf.push(lines[i++]);
    out += `<p>${buf.map(inline).join(' ')}</p>\n`;
  }
  return out;
}

