// Shared page shell for the Diorama documentation site (docs-site/).
// Every emitter (scripts/docs-site/build.mjs, scripts/docs-gallery/generate.mjs,
// scripts/docs-site/floorplans.mjs) routes its HTML through sitePage() and its
// stylesheet through writeSharedAssets() so the whole published site carries one
// topbar, one theme, and one CSS file. No runtime deps.

import fs from 'node:fs';
import path from 'node:path';

export function htmlEsc(s) {
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

