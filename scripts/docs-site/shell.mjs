// Write the shared stylesheet into <siteRoot>/assets/. Every emitter calls this
// so running any single script still yields a styled site.
export function writeSharedAssets(siteRoot) {
  fs.mkdirSync(path.join(siteRoot, 'assets'), { recursive: true });
  fs.writeFileSync(path.join(siteRoot, 'assets', 'site.css'), SITE_CSS);
}
